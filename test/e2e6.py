import asyncio, json
from playwright.async_api import async_playwright
URL='file:///home/claude/budget/dist/test.html'
FIX=open('test/fixtures/v1-state.json',encoding='utf8').read()
INIT="if(!localStorage.getItem('budget.planner.v1')) localStorage.setItem('budget.planner.v1', %s);"%json.dumps(FIX)
def chk(c,m): print(('ok   ' if c else 'FAIL ')+m)
async def main():
    async with async_playwright() as p:
        b=await p.chromium.launch(); ctx=await b.new_context(viewport={'width':390,'height':844},device_scale_factor=2)
        await ctx.add_init_script(INIT); pg=await ctx.new_page(); errs=[]; pg.on('pageerror',lambda e:errs.append(str(e)))
        await pg.goto(URL); await pg.wait_for_timeout(500)
        await pg.evaluate("S.settings.demo=false;commit()")
        await pg.click('[data-t=debts]')
        await pg.click('[data-a=debtNew]'); await pg.fill('#d-who','Анна'); await pg.fill('#d-amt','10000'); await pg.click('#ov [data-a=debtSave]')
        await pg.click('[data-a=debtNew]'); await pg.click('#ov [data-v=owed]'); await pg.fill('#d-who','Олег'); await pg.fill('#d-amt','25000'); await pg.click('#ov [data-a=debtSave]'); await pg.wait_for_timeout(200)
        t=await pg.inner_text('.hero'); chk('в плюсе' in t and '15 000' in t,'долги: итог сверху: '+t.replace('\n',' | '))
        await pg.screenshot(path='shots/70_debts.png')
        await pg.click('[data-t=home]'); await pg.wait_for_timeout(200)
        chk(await pg.locator('#app >> text=Долги').count()>0,'долги на главной')
        await pg.click('[data-t=budget]'); await pg.click('.cat >> nth=11'); await pg.click('[data-a=goalOpen]')
        await pg.set_input_files('input[data-c=goalFile]','/tmp/sky.png'); await pg.wait_for_timeout(600)
        await pg.fill('#g-name','Отпуск в Грузии'); await pg.fill('#g-target','150000'); await pg.fill('#g-date','01.07.2027')
        await pg.screenshot(path='shots/71_goal_sheet.png')
        await pg.click('[data-a=goalSave]'); await pg.wait_for_timeout(300); await pg.keyboard.press('Escape')
        photo=await pg.evaluate("S.cats.find(c=>c.goal).goal.photo.length")
        chk(photo>1000,'фото сохранено, %d символов'%photo)
        await pg.click('[data-t=home]'); await pg.wait_for_timeout(300)
        await pg.evaluate("document.querySelector('.goalc').scrollIntoView({block:'center'})"); await pg.wait_for_timeout(200)
        chk(await pg.locator('.goalc.has').count()==1,'цель с фото на главной')
        order=await pg.evaluate("[...document.querySelectorAll('#app .sect h2')].map(e=>e.textContent)")
        print(order); chk(order.index('Мои цели')<order.index('Категории') and order.index('Мои цели')>order.index('Ближайшие платежи'),'цель между платежами и категориями')
        await pg.screenshot(path='shots/72_home_goal.png')
        await pg.evaluate("window.scrollTo(0,0)"); await pg.screenshot(path='shots/73_home_top.png')
        await pg.click('[data-t=budget]'); await pg.screenshot(path='shots/74_budget_icons.png')
        print('errors:',errs); await b.close()
asyncio.run(main())
